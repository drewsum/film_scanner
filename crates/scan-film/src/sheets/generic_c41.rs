//! 200) + 1.26, as on Gold 200's). Every layer has the same curve and D-min, as a film with
//! no orange mask has. The spectral sensitivities are the sheets' mean, so the colorimetric
//! rendering is a typical film's. The dye densities are the masked films' mean, which an
//! unmasked film doesn't have; nothing uses them yet.

